#pragma once

#include <algorithm>
#include <vector>

/// The vector of wxWidgets is the vector of the standard library (wxUSE_STD_CONTAINERS).
template <class T>
using wxVector = std::vector<T>;

template <class T>
void wxVectorSort( wxVector<T>& aVector )
{
    std::sort( aVector.begin(), aVector.end() );
}
