/// The types of events the code declares (the class of their events is given by the handlers).
#define wxDECLARE_EVENT( name, type ) extern const wxEventType name
#define wxDECLARE_EXPORTED_EVENT( expdecl, name, type ) extern expdecl const wxEventType name
#define wxDEFINE_EVENT( name, type ) const wxEventType name = wxNewEventType()


class wxEvent
{
public:
    explicit wxEvent( int aId = 0, wxEventType aType = wxEVT_NULL ) :
            m_type( aType ),
            m_id( aId ),
            m_object( nullptr ),
            m_skipped( false )
    {
    }

    virtual ~wxEvent() = default;

    wxEventType GetEventType() const { return m_type; }
    void SetEventType( wxEventType aType ) { m_type = aType; }

    int GetId() const { return m_id; }
    void SetId( int aId ) { m_id = aId; }

    /// The widget the event comes from.
    QObject* GetEventObject() const { return m_object; }
    void SetEventObject( QObject* aObject ) { m_object = aObject; }

    /// Let the default processing of the event happen (the action of a standard button).
    void Skip( bool aSkip = true ) { m_skipped = aSkip; }
    bool GetSkipped() const { return m_skipped; }

    void StopPropagation() {}
    void ResumePropagation( int ) {}

private:
    wxEventType m_type;
    int         m_id;
    QObject*    m_object;
    bool        m_skipped;
};


class wxCommandEvent : public wxEvent
{
public:
    explicit wxCommandEvent( wxEventType aType = wxEVT_NULL, int aId = 0 ) :
            wxEvent( aId, aType ),
            m_int( 0 ),
            m_extraLong( 0 ),
            m_clientData( nullptr )
    {
    }

    int GetInt() const { return m_int; }
    void SetInt( int aInt ) { m_int = aInt; }

    long GetExtraLong() const { return m_extraLong; }
    void SetExtraLong( long aValue ) { m_extraLong = aValue; }

    const wxString& GetString() const { return m_string; }
    void SetString( const wxString& aString ) { m_string = aString; }

    bool IsChecked() const { return m_int != 0; }
    int GetSelection() const { return m_int; }

    void* GetClientData() const { return m_clientData; }
    void SetClientData( void* aData ) { m_clientData = aData; }

private:
    int      m_int;
    long     m_extraLong;
    wxString m_string;
    void*    m_clientData;
};


