/**
 * @file kiwx_events.h
 * The events of the wxWidgets compatibility layer of the Qt build (wxcompat): the data the
 * handlers of the dialogs of KiCad get, as the events of wxWidgets (wxCommandEvent,
 * wxFocusEvent, wxUpdateUIEvent...).
 *
 * The widgets of Qt don't send them: the Qt bases of the dialogs (generated by fbp2qt from the
 * wxFormBuilder files) make them from the signals of the widgets and call the handlers.
 */

