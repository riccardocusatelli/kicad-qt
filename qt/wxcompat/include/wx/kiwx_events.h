class wxMouseEvent : public wxEvent
{
public:
    explicit wxMouseEvent( wxEventType aType = wxEVT_NULL ) :
            wxEvent( 0, aType ),
            m_x( 0 ), m_y( 0 ), m_wheelRotation( 0 ),
            m_shift( false ), m_control( false ), m_alt( false )
    {
    }

    wxPoint GetPosition() const { return wxPoint( m_x, m_y ); }
    int GetX() const { return m_x; }
    int GetY() const { return m_y; }
    int GetWheelRotation() const { return m_wheelRotation; }
    int GetWheelDelta() const { return 120; }
    bool ShiftDown() const { return m_shift; }
    bool ControlDown() const { return m_control; }
    bool CmdDown() const { return m_control; }
    bool AltDown() const { return m_alt; }

    bool LeftDown() const { return GetEventType() == wxEVT_LEFT_DOWN; }
    bool LeftUp() const { return GetEventType() == wxEVT_LEFT_UP; }
    bool LeftDClick() const { return GetEventType() == wxEVT_LEFT_DCLICK; }
    bool RightDown() const { return GetEventType() == wxEVT_RIGHT_DOWN; }
    bool RightUp() const { return GetEventType() == wxEVT_RIGHT_UP; }

    int  m_x, m_y;
    int  m_wheelRotation;
    bool m_shift, m_control, m_alt;
};


class wxKeyEvent : public wxEvent
{
public:
    explicit wxKeyEvent( wxEventType aType = wxEVT_NULL ) :
            wxEvent( 0, aType ),
            m_keyCode( 0 ), m_modifiers( 0 )
    {
    }

    int GetKeyCode() const { return m_keyCode; }
    int GetModifiers() const { return m_modifiers; }
    bool HasAnyModifiers() const { return m_modifiers != 0; }
    bool ShiftDown() const { return m_modifiers & wxMOD_SHIFT; }
    bool ControlDown() const { return m_modifiers & wxMOD_CONTROL; }
    bool CmdDown() const { return m_modifiers & wxMOD_CMD; }
    bool AltDown() const { return m_modifiers & wxMOD_ALT; }

    int m_keyCode;
    int m_modifiers;
};


