class wxEvent
{
public:
    explicit wxEvent( int aId = 0, wxEventType aType = wxEVT_NULL ) :
            m_type( aType ),
            m_id( aId ),
            m_object( nullptr ),
            m_skipped( false )
    {
    }

    virtual ~wxEvent() = default;

    wxEventType GetEventType() const { return m_type; }
    void SetEventType( wxEventType aType ) { m_type = aType; }

    int GetId() const { return m_id; }
    void SetId( int aId ) { m_id = aId; }

    /// The widget the event comes from.
    QObject* GetEventObject() const { return m_object; }
    void SetEventObject( QObject* aObject ) { m_object = aObject; }

    /// Let the default processing of the event happen (the action of a standard button).
    void Skip( bool aSkip = true ) { m_skipped = aSkip; }
    bool GetSkipped() const { return m_skipped; }

    void StopPropagation() {}
    void ResumePropagation( int ) {}

private:
    wxEventType m_type;
    int         m_id;
    QObject*    m_object;
    bool        m_skipped;
};


