/**
 * The API of wxItemContainer (the list of strings of a choice, a combo box, a list box), with
 * the client data of the items.
 */
template <class QT>
class wxItemContainerCompat : public wxWindowCompat<QT>
{
public:
    using wxWindowCompat<QT>::wxWindowCompat;

    virtual unsigned int GetCount() const = 0;
    virtual wxString GetString( unsigned int aIndex ) const = 0;
    virtual void SetString( unsigned int aIndex, const wxString& aString ) = 0;
    virtual int GetSelection() const = 0;
    virtual void SetSelection( int aIndex ) = 0;
    virtual int Insert( const wxString& aItem, unsigned int aPos, void* aClientData ) = 0;
    virtual void Delete( unsigned int aIndex ) = 0;
    virtual void Clear() = 0;
    virtual void* GetClientData( unsigned int aIndex ) const = 0;
    virtual void SetClientData( unsigned int aIndex, void* aData ) = 0;

    bool IsEmpty() const { return GetCount() == 0; }

    int Append( const wxString& aItem ) { return Insert( aItem, GetCount(), nullptr ); }
    int AppendString( const wxString& aItem ) { return Append( aItem ); }
    int Append( const wxString& aItem, void* aClientData )
    {
        return Insert( aItem, GetCount(), aClientData );
    }

    void Append( const wxArrayString& aItems )
    {
        for( const wxString& item : aItems )
            Append( item );
    }

    void Append( const std::vector<wxString>& aItems )
    {
        for( const wxString& item : aItems )
            Append( item );
    }

    int Insert( const wxString& aItem, unsigned int aPos ) { return Insert( aItem, aPos, nullptr ); }

    void Set( const wxArrayString& aItems )
    {
        Clear();
        Append( aItems );
    }

    void Set( const std::vector<wxString>& aItems )
    {
        Clear();
        Append( aItems );
    }

    wxArrayString GetStrings() const
    {
        wxArrayString strings;

        for( unsigned int i = 0; i < GetCount(); ++i )
            strings.Add( GetString( i ) );

        return strings;
    }

    int FindString( const wxString& aString, bool aCaseSensitive = false ) const
    {
        for( unsigned int i = 0; i < GetCount(); ++i )
        {
            if( aCaseSensitive ? GetString( i ) == aString
                               : GetString( i ).IsSameAs( aString, false ) )
            {
                return int( i );
            }
        }

        return wxNOT_FOUND;
    }

    wxString GetStringSelection() const
    {
        int sel = GetSelection();
        return sel >= 0 ? GetString( sel ) : wxString();
    }

    bool SetStringSelection( const wxString& aString )
    {
        int index = FindString( aString );

        if( index == wxNOT_FOUND )
            return false;

        SetSelection( index );
        return true;
    }

    using wxWindowCompat<QT>::GetClientData;
    using wxWindowCompat<QT>::SetClientData;
};


