/**
 * @file kiwx_gui.h
 * The wxWidgets compatibility layer of the Qt build (wxcompat): the controls of the dialogs of
 * KiCad (wxCheckBox, wxTextCtrl, wxChoice...) are the widgets of Qt with the part of the API of
 * wxWidgets the dialogs use, so that the code of the dialogs builds on Qt unchanged.
 *
 * Each control derives from its Qt widget (wxCheckBox is a QCheckBox): the Qt bases of the
 * dialogs (generated by fbp2qt from the wxFormBuilder files) set them up with the API of Qt, the
 * code of the dialogs uses them with the API of wxWidgets.  In the GUI libraries of the Qt
 * build wxWindow is QWidget (a compile definition), as TOOLKIT_WINDOW.
 *
 * This is not wxWidgets: only what the dialogs of KiCad need is here, with the behavior of
 * Qt (layouts instead of sizers, no event tables).
 */

