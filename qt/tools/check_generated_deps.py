"""
check_generated_deps: the generated headers of a Ninja build come before the objects that
include them.

The Qt bases of the dialogs (fbp2qt) and the lexers (make_lexer) are generated by the custom
commands of their targets.  An object that includes such a header must depend on its generation
in the build graph, or a fresh parallel build can compile it first: it then finds another header
of the same name (the wxFormBuilder one of the sources) or none.  Incremental builds hide this.

Usage, in a Ninja build directory after a complete build (the headers each object includes come
from the dependency log of Ninja):

    check_generated_deps.py [<build directory>]

Prints the objects that include a generated header they do not depend on, with exit code 1.
"""

import collections
import os
import re
import subprocess
import sys


def read_graph( aBuildNinja ):
    """ The inputs (explicit, implicit and order-only) of each output of build.ninja. """
    text = open( aBuildNinja, encoding = 'utf-8' ).read().replace( '$\n', '' )
    inputs = {}

    for line in text.split( '\n' ):
        if not line.startswith( 'build ' ):
            continue

        m = re.match( r'build (.*?)(?<!\$): (\S+)(.*)', line )

        if not m:
            continue

        outs = [ o for o in re.split( r'(?<!\$) ', m.group( 1 ) ) if o and o != '|' ]
        ins = [ i for i in re.split( r'(?<!\$) ', m.group( 3 ).strip() )
                if i and i not in ( '|', '||' ) ]

        for out in outs:
            inputs[out] = ins

    return inputs


def main():
    build_dir = os.path.abspath( sys.argv[1] if len( sys.argv ) > 1 else '.' )
    root = build_dir + os.sep
    inputs = read_graph( os.path.join( build_dir, 'build.ninja' ) )

    def relative( aPath ):
        aPath = aPath.replace( '\\', '/' )
        prefix = root.replace( '\\', '/' )
        return os.path.normpath( aPath[len( prefix ):] if aPath.startswith( prefix ) else aPath )

    # The headers made by the build in the build directory (outputs of its edges).  The ones it
    # writes to the sources (the help texts from the Markdown files) are committed: always there.
    generated = { relative( o ) for o in inputs if o.endswith( ( '.h', '.hpp' ) ) }
    generated = { h for h in generated if not os.path.isabs( h ) }

    # The generated headers each object includes
    log = subprocess.run( [ 'ninja', '-C', build_dir, '-t', 'deps' ], capture_output = True,
                          text = True, check = True ).stdout
    includes = collections.defaultdict( set )
    current = None

    for line in log.split( '\n' ):
        if line and not line.startswith( ' ' ):
            current = line.split( ':' )[0]
        elif line.strip() and current:
            header = relative( line.strip() )

            if header in generated:
                includes[current].add( header )

    # What each target of objects depends on (the objects of a target share their dependencies)
    reached = {}

    def reachable( aTarget, aObject ):
        if aTarget not in reached:
            seen = set()
            stack = [ aObject ]

            while stack:
                node = stack.pop()

                if node in seen:
                    continue

                seen.add( node )
                stack += inputs.get( node, [] )

            reached[aTarget] = { relative( n ) for n in seen }

        return reached[aTarget]

    missing = collections.defaultdict( set )

    for obj, headers in includes.items():
        m = re.search( r'CMakeFiles/([^/]+)\.dir', obj.replace( '\\', '/' ) )
        target = m.group( 1 ) if m else obj

        for header in headers - reachable( target, obj ):
            missing[target].add( header )

    for target, headers in sorted( missing.items() ):
        print( f'{target} includes generated headers it does not depend on:' )

        for header in sorted( headers ):
            print( f'    {header}' )

    print( f'{len( includes )} objects include generated headers, '
           f'{len( missing )} targets miss dependencies' )
    return 1 if missing else 0


if __name__ == '__main__':
    sys.exit( main() )
